/* Fetches one headshot per photographer and writes portraits.js.
 *
 *   node tools/fetch-portraits.js            (needs UNSPLASH_ACCESS_KEY)
 *
 * Kept separate from fetch-photos.js on purpose: these are pictures OF the
 * photographer, not BY her, and they are the one thing in the app a real
 * photographer would always replace with her own. One query, one API call.
 *
 * Caveat worth knowing: the Unsplash License grants copyright permission but
 * explicitly does not grant rights relating to identifiable people. Putting a
 * real face on a fictional business persona is fine for a prototype carrying
 * a visible "these studios are fictional" disclaimer — it is not something to
 * ship commercially. In production each photographer uploads her own.
 */
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'portraits.js');
const KEY = (process.argv.find(a => a.startsWith('--key=')) || '').slice(6) ||
  process.env.UNSPLASH_ACCESS_KEY;

if (!KEY) {
  console.error('No Unsplash access key. Set UNSPLASH_ACCESS_KEY or pass --key=...');
  process.exit(1);
}

const QUERIES = ['professional woman portrait smiling', 'creative woman headshot'];

async function search(q) {
  const url = 'https://api.unsplash.com/search/photos?query=' + encodeURIComponent(q) +
    '&per_page=30&orientation=squarish&content_filter=high';
  const res = await fetch(url, {
    headers: { Authorization: 'Client-ID ' + KEY, 'Accept-Version': 'v1' },
  });
  if (!res.ok) throw new Error('Unsplash HTTP ' + res.status + ' for "' + q + '"');
  const json = await res.json();
  console.log('  ' + q.padEnd(36) + (json.results || []).length + ' results' +
    '  (calls left: ' + res.headers.get('x-ratelimit-remaining') + ')');
  return (json.results || []).map(r => ({
    id: (r.urls && r.urls.raw || '').match(/images\.unsplash\.com\/([^?]+)/)?.[1] || null,
    by: (r.user && r.user.name) || 'Unknown',
    u: (r.user && r.user.username) || '',
  })).filter(r => r.id);
}

(async () => {
  console.log('Fetching portraits');
  const seen = new Set();
  const out = [];
  for (const q of QUERIES) {
    for (const r of await search(q)) {
      if (seen.has(r.id)) continue;
      seen.add(r.id);
      out.push(r);
    }
  }

  console.log('\n' + out.length + ' unique portraits');
  if (out.length < 14) throw new Error('need at least 14, got ' + out.length);

  const body =
    '/* Generated by tools/fetch-portraits.js on ' + new Date().toISOString().slice(0, 10) + '.\n' +
    ' * One headshot per photographer, assigned in order by data.js. These are\n' +
    ' * stand-ins for a real upload — see the tool for the licensing caveat.\n' +
    ' */\n' +
    'const VEIL_PORTRAITS = ' + JSON.stringify(out.slice(0, 20)) + ';\n' +
    "if (typeof window !== 'undefined') window.VEIL_PORTRAITS = VEIL_PORTRAITS;\n" +
    "if (typeof module !== 'undefined') module.exports = VEIL_PORTRAITS;\n";

  fs.writeFileSync(OUT, body);
  console.log('wrote portraits.js — ' + Math.min(out.length, 20) + ' portraits');
})().catch(e => { console.error('\n' + e.message); process.exitCode = 1; });
